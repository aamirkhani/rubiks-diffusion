"""Sokoban head-to-head on fresh pull-generated instances (solvable by
construction). Reports solve rate by pull depth; failures include deadlocks
(irreversibility bites). Writes paper2_data/domain3_sokoban.json.
"""
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import torch

from domains.sokoban import SokobanEnv
from domains.train_sokoban import rollout
from model import PolicyNet, ValueNet

DEV = "cuda"


def load(ckpt):
    ck = torch.load(ckpt, map_location=DEV, weights_only=True)
    cfg = ck["cfg"]
    env = SokobanEnv(cfg["n"], cfg["n_boxes"], device=DEV)
    if cfg["method"] == "denoise":
        net = PolicyNet(env.S, env.M, cfg["h1"], cfg["h2"], cfg["blocks"],
                        vocab=env.vocab).to(DEV)
    else:
        net = ValueNet(env.S, cfg["h1"], cfg["h2"], cfg["blocks"],
                       vocab=env.vocab).to(DEV)
    net.load_state_dict(ck["net"])
    net.eval()
    return env, net, cfg


def main(B=5000):
    out = {"domain": "sokoban 8x8, 3 boxes (non-invertible pushes)",
           "instances_per_depth": B,
           "note": "instances generated by pulls => solvable by construction; "
                   "failures = policy deadlocks/timeouts"}
    for tag, ckpt in (("denoise", "runs/soko_diff/ckpt_latest.pt"),
                      ("davi", "runs/soko_davi/ckpt_latest.pt")):
        env, net, cfg = load(ckpt)
        res = {}
        for depth in (10, 25, 40, 60):
            g = torch.Generator(device=DEV).manual_seed(1000 + depth)
            w, go, b, a_, _ = env.instances_and_scramble(B, depth, generator=g)
            t0 = time.time()
            solved, actions = rollout(env, net, cfg["method"], w, go, b, a_,
                                      max_steps=4 * depth + 40)
            lens = (actions[solved] >= 0).sum(1).float()
            res[f"depth_{depth}"] = {
                "solve_rate": round(solved.float().mean().item(), 4),
                "avg_len": round(lens.mean().item(), 1) if solved.any() else None,
                "secs": round(time.time() - t0, 1)}
        out[tag] = res
        print(tag, json.dumps(res), flush=True)
    os.makedirs("paper2_data", exist_ok=True)
    with open("paper2_data/domain3_sokoban.json", "w") as f:
        json.dump(out, f, indent=2)
    print("saved paper2_data/domain3_sokoban.json")


if __name__ == "__main__":
    main()
